def plans_text() -> str:
    base_rate = PLANS["1m"]["price"] / (PLANS["1m"]["days"] / 30)
    lines = [
        "💳 <b>Выберите срок подписки</b>\n",
        "Чем больше срок — тем ниже цена за месяц.\n",
    ]
    for plan in PLANS.values():
        per_month = plan["price"] / (plan["days"] / 30)
        discount = round((1 - per_month / base_rate) * 100)
        discount_tag = f" 🎁 −{discount}%" if discount > 0 else ""
        lines.append(
            f"📦 <b>{plan['title']}</b> — <b>{plan['price']}₽</b>{discount_tag}\n"
            f"   ♾ Безлимитный трафик\n"
            f"   ~{per_month:.0f}₽/мес\n"
        )
    return "\n".join(lines)
